#!/usr/bin/env python3
"""Bind canonical source symbols to transient engine IDs; never save enum ordinals."""
import argparse
from pathlib import Path
import re

SOURCES = [
    ('species', 'RHH_SPECIES', 'SPECIES_', ['species.h']),
    ('move', 'RHH_MOVE', 'MOVE_', ['moves.h']),
    ('item', 'RHH_ITEM', 'ITEM_', ['items.h']),
    ('ability', 'RHH_ABILITY', 'ABILITY_', ['abilities.h']),
    ('type', 'RHH_TYPE', 'TYPE_', ['pokemon.h']),
    ('trainer', 'RHH_TRAINER', 'TRAINER_', ['opponents.h', 'opponents_frlg.h']),
    ('map', 'RHH_MAP', 'MAP_', ['map_groups.h']),
    ('area', 'RHH_AREA', 'MAPSEC_', ['region_map_sections.h']),
    ('music', 'RHH_MUSIC', 'MUS_', ['songs.h']),
]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    lines = ['/* Generated by native/generate_mod_content.py. */']
    for _, _, _, files in SOURCES:
        lines.extend(f'#include "constants/{name}"' for name in files)
    lines.append('static const struct RhhContentBinding sGameContent[] = {')
    for kind, enum, prefix, files in SOURCES:
        names = set()
        for name in files:
            source = (Path('include/constants') / name).read_text()
            source = re.sub(r'/\*.*?\*/|//[^\n]*', '', source, flags=re.S)
            names.update(re.findall(r'\b(' + prefix + r'[A-Z0-9_]+)\s*(?==|,|\n)', source))
            names.update(re.findall(r'^\s*#\s*define\s+(' + prefix + r'[A-Z0-9_]+)[ \t]+', source, flags=re.M))
        for name in sorted(names):
            suffix = name[len(prefix):]
            if suffix in {'COUNT', 'NONE', 'CUSTOM_END', 'EGG', 'INVALID', 'UNDEFINED', 'TM', 'HM', 'TM_', 'HM_'}:
                continue
            lines.append(f'    {{"rhh:{kind}/{suffix.lower()}", {enum}, {name}}},')
    for generation in range(1, 6):
        for role, name in enumerate(['wild', 'trainer', 'gym', 'champion']):
            lines.append(f'    {{"rhh:midi/gen{generation}/{name}", RHH_MIDI, {(generation - 1) * 4 + role + 1}}},')
    for generation in [12, 3, 4, 5]:
        lines.append(f'    {{"rhh:soundfont/gen{generation}", RHH_SOUNDFONT, {generation}}},')
    lines.extend(['};', ''])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines))

if __name__ == '__main__':
    main()
